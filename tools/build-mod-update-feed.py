#!/usr/bin/env python3
"""Build the static, SHA-256 protected mod feed for appt-engine.online."""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import shutil
import urllib.parse


MOD_IDS = {
    "black-shield-community": ("black shield community",),
    "controlify": ("controlify",),
    "fabric-api": ("fabric-api",),
    "ferritecore": ("ferritecore",),
    "immediatelyfast": ("immediatelyfast",),
    "javacraft-account": ("javacraft account",),
    "lithium": ("lithium",),
    "yacl": ("yet_another_config_lib", "yacl"),
}
DEFAULT_BASE_URL = "https://appt-engine.online/javacraft/mod-updates"


def mod_id(filename: str) -> str:
    folded = filename.casefold()
    matches = [mod_id for mod_id, needles in MOD_IDS.items()
               if any(needle in folded for needle in needles)]
    if len(matches) != 1:
        raise ValueError(f"Cannot map mod JAR to exactly one managed ID: {filename}")
    return matches[0]


def sha256(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", type=pathlib.Path,
                        default=pathlib.Path("dist/PS5/data/prospero-win/prefixes/minecraft-java/drive_c/JavaCraftPS5"),
                        help="Built JavaCraftPS5 folder containing modpacks/<Minecraft version>")
    parser.add_argument("--out", type=pathlib.Path, default=pathlib.Path("dist/JavaCraft-Update-Feed"),
                        help="Output folder that can be copied to the website document root")
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL,
                        help="Public HTTPS URL prefix for /javacraft/mod-updates")
    args = parser.parse_args()

    game = args.game.resolve()
    out = args.out.resolve()
    base = args.base_url.rstrip("/")
    parsed = urllib.parse.urlparse(base)
    if parsed.scheme != "https" or parsed.hostname != "appt-engine.online":
        raise SystemExit("The mod feed must use HTTPS on appt-engine.online.")
    if not (game / "modpacks").is_dir():
        raise SystemExit(f"Modpacks folder was not found: {game / 'modpacks'}")
    if out == game or game in out.parents:
        raise SystemExit("The output directory must not be inside the game payload.")
    if out.exists():
        marker = out / ".javacraft-feed"
        if not marker.is_file():
            raise SystemExit(f"Refusing to replace an unmarked output folder: {out}")
        shutil.rmtree(out)
    payload_root = out / "javacraft" / "mod-updates"
    files_root = payload_root / "files"
    files_root.mkdir(parents=True)
    (out / ".javacraft-feed").write_text("Generated by tools/build-mod-update-feed.py\n", encoding="ascii")

    versions: dict[str, list[dict[str, object]]] = {}
    for version_dir in sorted((game / "modpacks").iterdir()):
        if not version_dir.is_dir() or not re.fullmatch(r"26\.[0-9]+(?:\.[0-9]+)?", version_dir.name):
            continue
        jars = sorted(path for path in version_dir.iterdir()
                      if path.is_file() and path.suffix.casefold() == ".jar")
        if not jars:
            continue
        entries: list[dict[str, object]] = []
        ids: set[str] = set()
        version_files = files_root / version_dir.name
        version_files.mkdir()
        for jar in jars:
            identifier = mod_id(jar.name)
            if identifier in ids:
                raise SystemExit(f"More than one {identifier} JAR in Minecraft {version_dir.name}.")
            ids.add(identifier)
            digest = sha256(jar)
            destination = version_files / jar.name
            shutil.copy2(jar, destination)
            relative = "/".join(("files", version_dir.name, urllib.parse.quote(jar.name, safe="")))
            entries.append({
                "id": identifier,
                "file": jar.name,
                "url": f"{base}/{relative}",
                "size": jar.stat().st_size,
                "sha256": digest,
            })
        versions[version_dir.name] = entries

    if not versions:
        raise SystemExit("No versioned mod JARs were found in the selected game folder.")
    manifest = {
        "schemaVersion": 1,
        "channel": "stable",
        "versions": versions,
    }
    (payload_root / "manifest-v1.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Prepared {sum(map(len, versions.values()))} mod files for {len(versions)} Minecraft versions.")
    print(f"Upload the contents of {out} to the website document root.")
    print(f"Then confirm {base}/manifest-v1.json returns HTTP 200.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
